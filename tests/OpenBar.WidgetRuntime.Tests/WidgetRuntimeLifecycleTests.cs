    [Fact]
    public async Task CreatingAnUnknownWidgetIsRejected()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());

        await Assert.ThrowsAsync<WidgetValidationException>(
            () => harness.Runtime.CreateAsync("missing.widget"));

        Assert.Equal(0, harness.Store.Count);
    }

    [Fact]
    public async Task OperationsOnAMissingInstanceFailWithNotFound()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());

        await Assert.ThrowsAsync<WidgetNotFoundException>(
            () => harness.Runtime.StartAsync(Guid.NewGuid()));

        await Assert.ThrowsAsync<WidgetNotFoundException>(
            () => harness.Runtime.StopAsync(Guid.NewGuid()));
    }

    [Fact]
    public async Task AStartFromFaultedRequiresRestart()
    {
        await using var harness = RuntimeHarness.Create(
            TestDefinitions.Create(factory: static () => new RecordingWidget { ThrowOnInitialize = true }));

        await Assert.ThrowsAsync<WidgetLifecycleException>(
            () => harness.Runtime.CreateAsync(TestDefinitions.WidgetId));

        var info = harness.Runtime.GetInstances().Single();

        await Assert.ThrowsAsync<WidgetStateException>(
            () => harness.Runtime.StartAsync(info.Id));
    }

    [Fact]
    public async Task AStartedInstanceHonorsCancellation()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);
        _ = await harness.Runtime.StopAsync(info.Id);

        using var cts = new CancellationTokenSource();
        cts.Cancel();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(
            () => harness.Runtime.StartAsync(info.Id, cts.Token));

        Assert.Equal(WidgetInstanceState.Stopped, harness.Runtime.GetInstance(info.Id)!.State);
    }

    [Fact]
    public async Task InvalidPersistedSettingsFaultOnlyThatInstance()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());
        var seeded = await SeedAsync(
            harness.Store,
            TestDefinitions.WidgetId,
            "Broken",
            settingsJson: "{ invalid");

        var report = await harness.Runtime.StartAllAsync();

        Assert.Equal(0, report.Started);
        Assert.Single(report.Failures);
        Assert.Equal(WidgetInstanceState.Faulted, harness.Runtime.GetInstance(seeded.Id)!.State);
        Assert.Equal(1, harness.Store.Count);
    }

    private static Task<WidgetInstance> SeedAsync(
        InMemoryWidgetInstanceService store,
        string widgetId,
        string name,
        bool isEnabled = true,
        string settingsJson = "{}")
        => store.CreateAsync(new WidgetInstance
        {
            WidgetId = widgetId,
            InstanceName = name,
            IsEnabled = isEnabled,
            Width = 260,
            Height = 150,
            SettingsJson = settingsJson,
            SettingsSchemaVersion = 1
        });
}
