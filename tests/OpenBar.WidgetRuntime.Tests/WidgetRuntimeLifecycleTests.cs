using OpenBar.Application.Persistence;
using OpenBar.Domain.Widgets;
using OpenBar.WidgetRuntime.Tests.Fakes;
using OpenBar.Widgets.Abstractions;
using Xunit;

namespace OpenBar.WidgetRuntime.Tests;

public sealed class WidgetRuntimeLifecycleTests
{
    [Fact]
    public async Task CreatePersistsStartsAndOpensAWindow()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));

        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        Assert.Equal(WidgetInstanceState.Running, info.State);
        Assert.True(info.IsEnabled);
        Assert.Equal(1, harness.Store.Count);
        Assert.Single(harness.Windows.OpenWindows);
        Assert.Equal(1, factory.Last.InitializeCalls);
        Assert.Equal(1, factory.Last.StartCalls);
    }

    [Fact]
    public async Task AutoGeneratedNamesAreUnique()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());

        var first = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);
        var second = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        Assert.Equal("Test widget", first.InstanceName);
        Assert.Equal("Test widget 2", second.InstanceName);
        Assert.Equal(2, harness.Store.Count);
    }

    [Fact]
    public async Task MultipleInstancesOfTheSameWidgetKeepIndependentJson()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());

        var first = await harness.Runtime.CreateAsync(
            TestDefinitions.WidgetId,
            settingsJson: """{"value":1}""");
        var second = await harness.Runtime.CreateAsync(
            TestDefinitions.WidgetId,
            settingsJson: """{"value":2}""");

        Assert.Equal("""{"value":1}""", harness.Store.Find(first.Id)!.SettingsJson);
        Assert.Equal("""{"value":2}""", harness.Store.Find(second.Id)!.SettingsJson);
    }

    [Fact]
    public async Task SingleInstanceWidgetRejectsASecondInstance()
    {
        await using var harness = RuntimeHarness.Create(
            TestDefinitions.Create(allowsMultipleInstances: false));

        _ = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        await Assert.ThrowsAsync<WidgetValidationException>(
            () => harness.Runtime.CreateAsync(TestDefinitions.WidgetId));

        Assert.Equal(1, harness.Store.Count);
    }

    [Fact]
    public async Task StartingARunningInstanceIsIdempotent()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));

        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);
        await harness.Runtime.StartAsync(info.Id);
        await harness.Runtime.StartAsync(info.Id);

        Assert.Equal(1, factory.Last.StartCalls);
        Assert.Single(factory.Created);
    }

    [Fact]
    public async Task StoppingTwiceIsIdempotent()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        Assert.True(await harness.Runtime.StopAsync(info.Id));
        Assert.True(await harness.Runtime.StopAsync(info.Id));

        Assert.Equal(1, factory.Last.StopCalls);
        Assert.Equal(WidgetInstanceState.Stopped, harness.Runtime.GetInstance(info.Id)!.State);
    }

    [Fact]
    public async Task ConcurrentStartOnlyStartsTheWidgetOnce()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));

        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);
        _ = await harness.Runtime.StopAsync(info.Id);

        await Task.WhenAll(Enumerable.Range(0, 8)
            .Select(_ => harness.Runtime.StartAsync(info.Id)));

        Assert.Equal(2, factory.Created.Count);
        Assert.Equal(1, factory.Last.StartCalls);
    }

    [Fact]
    public async Task RestartCreatesAFreshWidgetAndReleasesThePreviousOne()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        await harness.Runtime.RestartAsync(info.Id);

        Assert.Equal(2, factory.Created.Count);
        Assert.Equal(1, factory.Created[0].StopCalls);
        Assert.Equal(1, factory.Created[0].DisposeCalls);
        Assert.Equal(1, factory.Created[1].StartCalls);
        Assert.Equal(WidgetInstanceState.Running, harness.Runtime.GetInstance(info.Id)!.State);
    }

    [Fact]
    public async Task InitializeFailureFaultsTheInstanceAndPreservesTheRow()
    {
        await using var harness = RuntimeHarness.Create(
            TestDefinitions.Create(factory: static () => new RecordingWidget { ThrowOnInitialize = true }));

        var ex = await Assert.ThrowsAsync<WidgetLifecycleException>(
            () => harness.Runtime.CreateAsync(TestDefinitions.WidgetId));

        Assert.NotNull(ex.InstanceId);
        Assert.Equal(1, harness.Store.Count);

        var info = harness.Runtime.GetInstances().Single();
        Assert.Equal(WidgetInstanceState.Faulted, info.State);
        Assert.False(string.IsNullOrWhiteSpace(info.LastError));
        Assert.Empty(harness.Windows.OpenWindows);
    }

    [Fact]
    public async Task WindowOpenFailureFaultsTheInstanceAndPreservesTheRow()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        harness.Windows.ThrowOnOpen = true;

        await Assert.ThrowsAsync<WidgetLifecycleException>(
            () => harness.Runtime.CreateAsync(TestDefinitions.WidgetId));

        Assert.Equal(1, harness.Store.Count);
        Assert.Equal(WidgetInstanceState.Faulted, harness.Runtime.GetInstances().Single().State);
        Assert.True(factory.Last.StopCalls >= 1);
    }

    [Fact]
    public async Task AWidgetFailureDoesNotPreventOtherInstancesFromRunning()
    {
        var goodFactory = new RecordingWidgetFactory();
        var bad = TestDefinitions.Create("test.bad", static () => new RecordingWidget { ThrowOnInitialize = true });
        var good = TestDefinitions.Create("test.good", goodFactory.Create);

        await using var harness = RuntimeHarness.Create(bad, good);
        _ = await SeedAsync(harness.Store, "test.bad", "Bad");
        _ = await SeedAsync(harness.Store, "test.good", "Good");

        var report = await harness.Runtime.StartAllAsync();

        Assert.Equal(1, report.Started);
        Assert.Single(report.Failures);
        Assert.Equal(WidgetInstanceState.Faulted, harness.Runtime.GetInstances().Single(i => i.WidgetId == "test.bad").State);
        Assert.Equal(WidgetInstanceState.Running, harness.Runtime.GetInstances().Single(i => i.WidgetId == "test.good").State);
        Assert.Equal(1, goodFactory.Last.StartCalls);
    }

    [Fact]
    public async Task StartAllRecoversPersistedEnabledInstances()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var seeded = await SeedAsync(harness.Store, TestDefinitions.WidgetId, "Recovered");

        var report = await harness.Runtime.StartAllAsync();

        Assert.Equal(1, report.Started);
        Assert.Empty(report.Failures);
        Assert.Equal(WidgetInstanceState.Running, harness.Runtime.GetInstance(seeded.Id)!.State);
        Assert.Single(harness.Windows.OpenWindows);
    }

    [Fact]
    public async Task StartAllSkipsDisabledInstances()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        _ = await SeedAsync(harness.Store, TestDefinitions.WidgetId, "Disabled", isEnabled: false);

        var report = await harness.Runtime.StartAllAsync();

        Assert.Equal(0, report.Started);
        Assert.Equal(1, report.SkippedDisabled);
        Assert.Empty(factory.Created);
    }

    [Fact]
    public async Task UnavailableWidgetInstancesArePreserved()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());
        _ = await SeedAsync(harness.Store, "missing.widget", "Orphan");

        var report = await harness.Runtime.StartAllAsync();

        Assert.Equal(1, report.Unavailable);
        Assert.Equal(1, harness.Store.Count);
        Assert.Equal(WidgetInstanceState.Unavailable, harness.Runtime.GetInstances().Single().State);
    }

    [Fact]
    public async Task StartAllIsIdempotent()
    {
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create());

        _ = await harness.Runtime.StartAllAsync();
        var second = await harness.Runtime.StartAllAsync();

        Assert.True(second.AlreadyStarted);
    }

    [Fact]
    public async Task ClosingTheWidgetWindowStopsTheInstance()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        harness.Windows.RaiseCloseRequested(info.Id);

        await TestHelpers.WaitUntilAsync(
            () => harness.Runtime.GetInstance(info.Id)!.State == WidgetInstanceState.Stopped);

        Assert.Equal(1, factory.Last.StopCalls);
    }

    [Fact]
    public async Task DeletingStopsTheWidgetAndRemovesThePersistedRow()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        Assert.True(await harness.Runtime.DeleteAsync(info.Id));

        Assert.Equal(0, harness.Store.Count);
        Assert.Null(harness.Runtime.GetInstance(info.Id));
        Assert.Equal(1, factory.Last.StopCalls);
        Assert.Equal(1, factory.Last.DisposeCalls);
        Assert.False(await harness.Runtime.DeleteAsync(info.Id));
    }

    [Fact]
    public async Task DeleteKeepsTheRowWhenStoppingFails()
    {
        await using var harness = RuntimeHarness.Create(
            TestDefinitions.Create(factory: static () => new RecordingWidget { ThrowOnStop = true }));

        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        await Assert.ThrowsAsync<WidgetLifecycleException>(
            () => harness.Runtime.DeleteAsync(info.Id));

        Assert.Equal(1, harness.Store.Count);
        Assert.Equal(WidgetInstanceState.Faulted, harness.Runtime.GetInstance(info.Id)!.State);
    }

    [Fact]
    public async Task DisablingStopsTheWidgetAndPersistsTheFlag()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        await harness.Runtime.SetEnabledAsync(info.Id, false);

        var stored = harness.Store.Find(info.Id)!;
        Assert.False(stored.IsEnabled);
        Assert.Equal(1, factory.Last.StopCalls);
        Assert.Equal(WidgetInstanceState.Stopped, harness.Runtime.GetInstance(info.Id)!.State);
    }

    [Fact]
    public async Task EnablingStartsTheWidgetAgain()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);
        await harness.Runtime.SetEnabledAsync(info.Id, false);

        await harness.Runtime.SetEnabledAsync(info.Id, true);

        Assert.True(harness.Store.Find(info.Id)!.IsEnabled);
        Assert.Equal(2, factory.Created.Count);
        Assert.Equal(1, factory.Last.StartCalls);
        Assert.Equal(WidgetInstanceState.Running, harness.Runtime.GetInstance(info.Id)!.State);
    }

    [Fact]
    public async Task UpdatingSettingsPersistsAndNotifiesTheWidget()
    {
        var factory = new RecordingWidgetFactory();
        await using var harness = RuntimeHarness.Create(TestDefinitions.Create(factory: factory.Create));
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        await harness.Runtime.UpdateSettingsAsync(info.Id, """{"value":42}""", 2);

        var stored = harness.Store.Find(info.Id)!;
        Assert.Equal("""{"value":42}""", stored.SettingsJson);
        Assert.Equal(2, stored.SettingsSchemaVersion);
        Assert.Single(factory.Last.AppliedSettings);
        Assert.Equal(2, factory.Last.AppliedSettings[0].SchemaVersion);
    }

    [Fact]
    public async Task SettingsAreRejectedWhenTheWidgetDoesNotDeclareTheCapability()
    {
        var definition = TestDefinitions.Create();
        var noSettings = definition with
        {
            Metadata = definition.Metadata with { Capabilities = WidgetCapabilities.PeriodicUpdates }
        };

        await using var harness = RuntimeHarness.Create(noSettings);
        var info = await harness.Runtime.CreateAsync(TestDefinitions.WidgetId);

        await Assert.ThrowsAsync<WidgetValidationException>(
            () => harness.Runtime.UpdateSettingsAsync(info.Id, """{"value":1}"""));

        Assert.Equal("{}", harness.Store.Find(info.Id)!.SettingsJson);
    }

    [Fact]
    public async Task InvalidJsonIsRejectedBeforePersistence()
